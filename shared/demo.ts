export function createDemoProject(): Project {
  let project = createProject();
  project = { ...project, name: 'StaffPlanner — вымышленный пример', description: 'Синтетический учебный проект про расписание смен. Спрос, цены, рынок и команда не подтверждены.', isDemo: true, stageLabel: 'Подготовленный пример' };
  const values: Record<string, string> = {
    idea: 'Telegram mini-app для расписания смен и согласования обменов', geography: 'Россия — условный старт',
    audience: 'Небольшие магазины с посменной работой', user: 'Сотрудник и заместитель директора', buyer: 'Директор или владелец магазина',
    price: '1 000 ₽ / магазин / месяц — условная цена', channel: 'SEO — гипотеза канала', team: 'Соло-разработчик — вымышленная роль',
    timeline: '8 недель MVP; 3 месяца проверки канала; расписание на две недели',
  };
  const facts: Fact[] = Object.entries(values).map(([key, value]) => ({ key, value, provenance: 'hypothesis', note: 'Вымышленный демонстрационный сценарий; не подтверждён пользователем или внешним исследованием.' }));
  project = updateFacts(project, facts);
  for (const id of STAGE_IDS) {
    project = saveArtifact(project, id, { title: MODULES[id].title, body: `> Вымышленный пример. Все числовые вводные — гипотезы. Без веб-поиска.\n\n${demoBodies[id]}` });
    const state = project.modules[id];
    project = { ...project, modules: { ...project.modules, [id]: { ...state, artifact: { ...state.artifact!, assessment: assessArtifact(id, state.artifact!.body, project.facts) } } } };
  }
  project.calculations = {
    market: calculateMarket({ totalBuyers: 10_000, reachableBuyers: 1_000, targetBuyers: 10, price: 1_000, period: 'месяц' }),
    economics: calculateEconomics({ customers: 10, price: 1_000, period: 'месяц' }),
  };
  return project;
}
