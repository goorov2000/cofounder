import { test, expect } from '@playwright/test';
import { createProject, saveArtifact } from '../../shared/domain';
import type { ChatRequest } from '../../shared/types';
import { expandRoute } from './project-panel';

test('manual materials guide new stages; starting sends immediately while navigation preserves drafts without calling AI', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 720 });
  await page.route('**/api/status', route => route.fulfill({ json: { configured: true, reason: '', model: 'mock-only', searchEnabled: false } }));
  const sent: ChatRequest[] = [];
  await page.route('**/api/chat', async route => {
    const payload = route.request().postDataJSON() as ChatRequest;
    sent.push(payload);
    await route.fulfill({ json: { requestId: payload.requestId, model: 'mock-only', reply: { message: 'Контекст получен тестовой заглушкой.', choices: [], artifactDraft: null, proposedFacts: [] } } });
  });
  const idea = 'Выездной ремонт велосипедов в Петрозаводске. Начинаю один. Возможность работы в другом городе пока не решена.';
  const audience = 'Владельцы городских велосипедов в Петрозаводске. Пользователь и плательщик — владелец велосипеда. Численность неизвестна. Интервью ещё не проводил.';
  let project = saveArtifact(createProject(),'idea',{title:'Выездной ремонт',body:idea});
  project = saveArtifact(project,'audience',{title:'Покупатели ремонта',body:audience});
  project = saveArtifact(project,'competitors',{title:'Альтернативы',body:'Ручной способ; внешние сведения ещё не проверены.'});
  await page.addInitScript(project=>{if(!localStorage.getItem('cofounder.workspace.v1'))localStorage.setItem('cofounder.workspace.v1',JSON.stringify({version:1,activeProjectId:project.id,projects:[project]}));},project);
  await page.goto('/');
  const welcome = page.locator('.workspace-welcome');
  await expandRoute(page);
  await page.locator('.stage-list').getByRole('button', { name: 'Рынок', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Размер рынка', exact: true })).toBeVisible();
  await expect(welcome).toContainText('TAM / SAM / SOM');
  await expect(welcome).not.toContainText('В какой географии');
  expect(sent).toHaveLength(0);
  await page.screenshot({ path: '.autopilot/2026-11-14-cofounder--wip/evidence/f2/start-manual-1280.png', fullPage: true });
  await welcome.getByRole('button', { name: 'Начать этап', exact: true }).click();
  const input = page.getByRole('textbox', { name: 'Сообщение', exact: true });
  await expect(page.getByText('Контекст получен тестовой заглушкой.', { exact: true })).toBeVisible();
  expect(sent).toHaveLength(1);
  expect(sent[0].message).toBe('Начнём этап «Размер рынка». Учти то, что мы уже обсудили о проекте.');
  expect(sent[0].moduleId).toBe('market');
  expect(sent[0].context.facts).toEqual([]);
  expect(sent[0].context.artifacts.map(material => material.body)).toEqual([idea, audience, 'Ручной способ; внешние сведения ещё не проверены.']);
  await page.screenshot({ path: '.repair/2026-11-16-stage-intro/short-starter-1280-light.png' });
  await expect(input).toHaveValue('');
  await expect(input).toBeFocused();
  const draft = 'Хочу уточнить размер рынка';
  await input.fill(draft);
  await page.locator('.stage-list').getByRole('button', { name: 'Идея', exact: true }).click();
  await input.fill('Перейди к рынку.');
  await page.getByRole('button', { name: 'Отправить', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Размер рынка', exact: true })).toBeVisible();
  await expect(input).toHaveValue(draft);
  await page.reload();
  await expect(input).toHaveValue(draft);
  await expect(welcome.getByRole('button', { name: 'Начать этап', exact: true })).toHaveCount(0);
  await expect(page.getByText('Контекст получен тестовой заглушкой.', { exact: true })).toBeVisible();
  expect(sent).toHaveLength(1);
});
